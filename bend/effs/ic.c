#define NT_EXT 2
#define NT_ERA 3
#define NT_ZERO 4
#define NT_GATE 5
#define NT_CONST 6
#define NT_REF 7
#define NT_PAIR 8
#define NT_ABORTED 9
#define NT_DUP 10
#define NT_SPLIT 11
#define NT_SETENV 12
#define NT_APPLY 13
#define NT_SCRUT 14
#define NT_LEFT 16
#define NT_RIGHT 17
#define NT_STUCK 18
#define NT_KINDS 19

