-- |Something legal but probably unintended.
data BindWarning
  = Shadows LocTag String LocTag
    -- ^ The name bound at the first location shadows the same name bound
    -- at the second.
  | ShadowsRequirement LocTag String
    -- ^ A variable has the name of a requirement that passes it by without
    -- being captured (variables never supply requirements).
  | UnusedBinding LocTag String
    -- ^ A let entry that no mention resolves to.
  deriving (Eq, Show)

renderBindWarning :: BindWarning -> String
renderBindWarning = \case
  Shadows loc name other ->
    "warning: " <> show name <> " shadows the binding at "
    <> fromMaybe (renderLocTagVerbose other) (renderLocTagCompact other)
    <> atLoc loc
  ShadowsRequirement loc name ->
    "warning: variable " <> show name <> " does not supply the requirement "
    <> show name <> " of what its body mentions" <> atLoc loc
  UnusedBinding loc name -> "warning: " <> show name <> " is never used" <> atLoc loc
  where
    atLoc loc = maybe "" (" at " <>) (renderLocTagCompact loc)

bindWarningLoc :: BindWarning -> LocTag
bindWarningLoc = \case
  Shadows loc _ _          -> loc
  ShadowsRequirement loc _ -> loc
  UnusedBinding loc _      -> loc

-- |The lifted parameter standing for requirement @r@. Generated names
-- start with @_@, which a source identifier cannot.
requirementParam :: String -> String
requirementParam = ("__req_" <>)

-- |The unique name a module's top-level definition goes by in the output.
-- @::@ cannot occur in a source identifier.
topLevelName :: String -> String -> String
topLevelName moduleName key = moduleName <> "::" <> key

-- |Generated by an earlier stage, so exempt from shadowing and unused
-- warnings, and never renamed.
generated :: String -> Bool
generated = ("_" `isPrefixOf`)

type EntryId = Int

-- |What a binder key refers to.
data Target = EntryTarget EntryId | BuiltinTarget

data BinderKind = LetBinder | ModuleBinder | BuiltinBinder
  deriving Eq

data Frame
  = VarFrame (Map String LocatedName)
    -- ^ Lambda or pattern variables: source name to output name (which
    -- keeps the source location).
  | BinderFrame BinderKind (Map String (LocTag, Target))

data Ctx = Ctx
  { ctxFrames     :: [Frame] -- ^ innermost first
  , ctxQualifiers :: Set String -- ^ import qualifiers of the module
  , ctxModule     :: String
  }

push :: Frame -> Ctx -> Ctx
push frame ctx = ctx { ctxFrames = frame : ctxFrames ctx }

data EntryDef = EntryDef
  { edKey  :: LocatedName
  , edOut  :: String -- ^ name in the output
  , edBody :: ExpandedSurfaceTerm
  , edCtx  :: Ctx -- ^ definition site, including its own binder
  }

-- |Where a requirement came from: the occurrence, then each entry it was
-- inherited through, innermost first.
data Trail = Trail LocTag [(String, LocTag)]

-- |Requirement names, each with the trail of its first occurrence.
type Req = Map String Trail

data St = St
  { stNext     :: !Int
  , stDefs     :: Map EntryId EntryDef
  , stDone     :: Map EntryId (Req, ExpandedSurfaceTerm)
  , stActive   :: [EntryId] -- ^ entries being elaborated, innermost first
  , stUsed     :: Set EntryId
  , stWarnings :: [(String, BindWarning)] -- ^ with their module, newest first
  }

type BindM = StateT St (Either ResolverError)

failWith :: ResolverError -> BindM a
failWith = lift . Left

warn :: Ctx -> BindWarning -> BindM ()
warn ctx w = modify' $ \st -> st { stWarnings = (ctxModule ctx, w) : stWarnings st }

fresh :: BindM Int
fresh = do
  n <- gets stNext
  modify' $ \st -> st { stNext = n + 1 }
  pure n

getDef :: EntryId -> BindM EntryDef
getDef i = gets (Map.lookup i . stDefs) >>= \case
  Just def -> pure def
  Nothing  -> error "Telomare.Bind: unregistered entry"

-- |The builtins, outermost in every chain: defined everywhere, so never a
-- requirement and never supplied.
builtinFrame :: Frame
builtinFrame = BinderFrame BuiltinBinder . Map.fromList $
  [ (name, (BuiltinLoc name, BuiltinTarget)) | name <- builtinNames ]

-- |The nearest frame binding a name.
data Hit = VarHit LocatedName | BinderHit BinderKind LocTag Target

lookupFrames :: String -> [Frame] -> Maybe Hit
lookupFrames name = foldr look Nothing where
  look frame rest = case frame of
    VarFrame vars | Just out <- Map.lookup name vars -> Just (VarHit out)
    BinderFrame kind keys | Just (loc, t) <- Map.lookup name keys -> Just (BinderHit kind loc t)
    _ -> rest

-- |The innermost binder (lambdas skipped) with a key.
lookupBinders :: String -> [Frame] -> Maybe Target
lookupBinders name = foldr look Nothing where
  look frame rest = case frame of
    BinderFrame _ keys | Just (_, t) <- Map.lookup name keys -> Just t
    _                                                        -> rest

isQualified :: Ctx -> String -> Bool
isQualified ctx name = any (\q -> (q <> ".") `isPrefixOf` name) (ctxQualifiers ctx)

genLoc :: String -> LocTag -> LocTag
genLoc why loc = GeneratedLoc why (Just loc)

var :: LocTag -> String -> ExpandedSurfaceTerm
var loc name = loc :< UnprocessedParsedTermL (VarF name)

-- |Elaborate a term, returning it with the requirements that escape to the
-- innermost enclosing entry.
elab :: Ctx -> ExpandedSurfaceTerm -> BindM (ExpandedSurfaceTerm, Req)
elab ctx (loc :< term) = case term of
  UnprocessedParsedTermL (VarF name) -> occurrence ctx loc name
  UnprocessedParsedTermL (LamF v body) -> do
    (frame, v') <- bindVariables ctx [v] >>= \case
      (frame, [v']) -> pure (frame, v')
      _ -> error "Telomare.Bind: one variable in, one out"
    (body', req) <- elab (push frame ctx) body
    warnPassingRequirements ctx [v] req
    pure (loc :< UnprocessedParsedTermL (LamF v' body'), req)
  LetUPF bindings body -> elabLet ctx loc bindings body
  CaseUPF scrutinee alternatives -> do
    (scrutinee', reqS) <- elab ctx scrutinee
    alternatives' <- forM alternatives $ \(p, body) -> do
      (p', reqP) <- elabGuards ctx p
      let binders = patternBinders p
      (frame, binders') <- bindVariables ctx binders
      (body', reqB) <- elab (push frame ctx) body
      warnPassingRequirements ctx binders reqB
      let renames = Map.fromList $ zip (locatedNameText <$> binders) binders'
      pure ((renamePattern renames p', body'), reqP <> reqB)
    pure (loc :< CaseUPF scrutinee' (fst <$> alternatives'), reqS <> foldMap snd alternatives')
  other -> do
    layer <- traverse (elab ctx) other
    pure (loc :< fmap fst layer, foldMap snd layer)

-- |Guards in a pattern's annotations, elaborated outside its variables.
elabGuards :: Ctx -> PatternA -> BindM (PatternA, Req)
elabGuards ctx (Fix p) = case p of
  PatternAnnotatedF inner (AnnotatedEST g) -> do
    (inner', reqI) <- elabGuards ctx inner
    (g', reqG) <- elab ctx g
    pure (Fix $ PatternAnnotatedF inner' (AnnotatedEST g'), reqI <> reqG)
  other -> do
    layer <- traverse (elabGuards ctx) other
    pure (Fix $ fst <$> layer, foldMap snd layer)

renamePattern :: Map String LocatedName -> PatternA -> PatternA
renamePattern renames (Fix p) = Fix $ case p of
  PatternVarF name -> PatternVarF $ Map.findWithDefault name (locatedNameText name) renames
  other            -> renamePattern renames <$> other

-- |Bring lambda or pattern variables into scope. A variable with the name
-- of an enclosing let key is renamed, so that an argument supplied from
-- that key below it cannot be captured.
bindVariables :: Ctx -> [LocatedName] -> BindM (Frame, [LocatedName])
bindVariables ctx names = do
  outs <- forM names $ \name -> do
    let text = locatedNameText name
        loc = locatedNameLoc name
    if generated text then pure name else do
      case lookupFrames text (ctxFrames ctx) of
        Just (BinderHit kind keyLoc _) | kind /= BuiltinBinder -> warn ctx (Shadows loc text keyLoc)
        _ -> pure ()
      if any (letKey text) (ctxFrames ctx)
        then (\n -> locatedName loc ("__var_" <> text <> "_" <> show n)) <$> fresh
        else pure name
  pure (VarFrame . Map.fromList $ zip (locatedNameText <$> names) outs, outs)
  where
    letKey text = \case
      BinderFrame LetBinder keys -> Map.member text keys
      _                          -> False

warnPassingRequirements :: Ctx -> [LocatedName] -> Req -> BindM ()
warnPassingRequirements ctx names req = forM_ names $ \name ->
  when (Map.member (locatedNameText name) req) $
    warn ctx (ShadowsRequirement (locatedNameLoc name) (locatedNameText name))

occurrence :: Ctx -> LocTag -> String -> BindM (ExpandedSurfaceTerm, Req)
occurrence ctx loc name = case lookupFrames name (ctxFrames ctx) of
  Just (VarHit out) -> pure (var loc (locatedNameText out), mempty)
  Just (BinderHit _ _ target) -> mention ctx loc name target
  Nothing
    | isQualified ctx name -> failWith (UnboundQualifiedName loc name)
    | otherwise -> pure (var loc (requirementParam name), Map.singleton name (Trail loc []))

-- |A mention of a binder key, applied to its requirements resolved here.
mention :: Ctx -> LocTag -> String -> Target -> BindM (ExpandedSurfaceTerm, Req)
mention ctx loc name = \case
  BuiltinTarget -> pure (var loc name, mempty)
  EntryTarget i -> do
    modify' $ \st -> st { stUsed = Set.insert i (stUsed st) }
    def <- getDef i
    req <- requirementsOf i
    let key = edKey def
        through (Trail occ via) = Trail occ (via <> [(locatedNameText key, locatedNameLoc key)])
        argLoc = genLoc "supplied requirement" loc
    args <- forM (Map.toAscList req) $ \(r, trail) -> supply ctx argLoc r (through trail)
    pure ( foldl (\f a -> argLoc :< UnprocessedParsedTermL (AppF f a)) (var loc (edOut def)) (fst <$> args)
         , foldMap snd args )

supply :: Ctx -> LocTag -> String -> Trail -> BindM (ExpandedSurfaceTerm, Req)
supply ctx loc r trail = case lookupBinders r (ctxFrames ctx) of
  Just target -> mention ctx loc r target
  Nothing     -> pure (var loc (requirementParam r), Map.singleton r trail)

-- |An entry's requirements, elaborating it on first demand.
requirementsOf :: EntryId -> BindM Req
requirementsOf i = gets (Map.lookup i . stDone) >>= \case
  Just (req, _) -> pure req
  Nothing -> do
    active <- gets stActive
    when (i `elem` active) $ do
      -- report the cycle from its earliest-written member, as
      -- 'Telomare.Resolve.topologicalSort' does
      let members = reverse (i : takeWhile (/= i) active)
          (before, from) = break (== minimum members) members
          path = from <> before
      names <- traverse (fmap (locatedNameText . edKey) . getDef) path
      failWith . DefinitionCycle $ names <> take 1 names
    def <- getDef i
    modify' $ \st -> st { stActive = i : stActive st }
    (body', req) <- elab (edCtx def) (edBody def)
    let keyLoc = locatedNameLoc (edKey def)
        lamLoc = genLoc "lifted requirement" keyLoc
        lifted = foldr (\r b -> lamLoc :< UnprocessedParsedTermL (LamF (locatedName lamLoc (requirementParam r)) b))
                       body' (Map.keys req)
    modify' $ \st -> st { stActive = drop 1 (stActive st)
                        , stDone = Map.insert i (req, lifted) (stDone st) }
    pure req

elaborated :: EntryId -> BindM ExpandedSurfaceTerm
elaborated i = requirementsOf i >> gets (maybe (error "Telomare.Bind: entry not done") snd . Map.lookup i . stDone)

duplicateKeys :: [LocatedName] -> Maybe LocatedName
duplicateKeys = go Set.empty where
  go _ [] = Nothing
  go seen (n : ns)
    | locatedNameText n `Set.member` seen = Just n
    | otherwise = go (Set.insert (locatedNameText n) seen) ns

elabLet :: Ctx -> LocTag -> [(LocatedName, ExpandedSurfaceTerm)] -> ExpandedSurfaceTerm
        -> BindM (ExpandedSurfaceTerm, Req)
elabLet ctx loc bindings body = do
  forM_ (duplicateKeys (fst <$> bindings)) $ \n ->
    failWith (DuplicateDefinition (locatedNameLoc n) (locatedNameText n))
  forM_ (fst <$> bindings) $ \key -> do
    let text = locatedNameText key
    if generated text then pure () else case lookupFrames text (ctxFrames ctx) of
      Just (BinderHit kind other _) | kind /= BuiltinBinder -> warn ctx (Shadows (locatedNameLoc key) text other)
      Just (VarHit other) -> warn ctx (Shadows (locatedNameLoc key) text (locatedNameLoc other))
      _ -> pure ()
  ids <- forM bindings $ const fresh
  let frame = BinderFrame LetBinder . Map.fromList $
        [ (locatedNameText key, (locatedNameLoc key, EntryTarget i)) | (i, (key, _)) <- zip ids bindings ]
      ctx' = push frame ctx
  forM_ (zip ids bindings) $ \(i, (key, value)) ->
    modify' $ \st -> st { stDefs = Map.insert i (EntryDef key (locatedNameText key) value ctx') (stDefs st) }
  (body', reqB) <- elab ctx' body
  bindings' <- forM (zip ids bindings) $ \(i, (key, _)) -> (,) key <$> elaborated i
  used <- gets stUsed
  forM_ (zip ids bindings) $ \(i, (key, _)) ->
    when (not (generated (locatedNameText key)) && Set.notMember i used) $
      warn ctx (UnusedBinding (locatedNameLoc key) (locatedNameText key))
  pure (loc :< LetUPF bindings' body', reqB)

-- |Reachable modules' top-level definitions, in the order the old import
-- flattening listed them (imports expanded in place, each module once).
moduleOrder :: ExpandedModules -> String -> Either ResolverError [String]
moduleOrder modules root = reverse . snd <$> visit [] ([], []) root where
  visit stack (seen, acc) name
    | name `elem` stack = Left . ImportCycle $ dropWhile (/= name) stack <> [name]
    | name `elem` seen = Right (seen, acc)
    | otherwise = case lookup name modules of
        Nothing -> Left $ ModuleNotFound name
        Just items ->
          let imports = [ locatedNameText (parsedImportModule d) | ExpandedModuleImport d <- items ]
          in second (name :) <$> foldl
               (\r i -> r >>= \sa -> visit (stack <> [name]) sa i)
               (Right (name : seen, acc)) imports

data ModuleInfo = ModuleInfo
  { miKeys     :: Map String (LocTag, EntryId)
  , miBindings :: [(LocatedName, EntryId)]
  }

-- |Resolve, elaborate and diagnose a program. The output is closed: one
-- let of every needed top-level definition around @main@'s body. Each
-- warning comes with the name of the module it is about.
bindProgram :: ExpandedModules -> String
            -> Either ResolverError (ExpandedSurfaceTerm, [(String, BindWarning)])
bindProgram modules mainModule = do
  order <- moduleOrder modules mainModule
  (term, st) <- runStateT (program order) (St 0 Map.empty Map.empty [] Set.empty [])
  pure (term, reverse (stWarnings st))
  where
    itemsOf name = fromMaybe [] (lookup name modules)
    program order = do
      -- allocate every module's store first: chains refer across modules
      infos <- fmap Map.fromList . forM order $ \name -> do
        let bindings = [ (key, value) | ExpandedModuleBinding key value <- itemsOf name ]
        forM_ (duplicateKeys (fst <$> bindings)) $ \n ->
          failWith (DuplicateDefinition (locatedNameLoc n) (locatedNameText n))
        ids <- forM bindings $ const fresh
        pure (name, ModuleInfo
          (Map.fromList [ (locatedNameText k, (locatedNameLoc k, i)) | (i, (k, _)) <- zip ids bindings ])
          [ (k, i) | (i, (k, _)) <- zip ids bindings ])
      forM_ order $ \name -> do
        ctx <- moduleCtx infos name
        let bindings = [ (key, value) | ExpandedModuleBinding key value <- itemsOf name ]
            info = infos Map.! name
        forM_ (zip (miBindings info) bindings) $ \((key, i), (_, value)) ->
          modify' $ \st -> st { stDefs = Map.insert i
            (EntryDef key (topLevelName name (locatedNameText key)) value ctx) (stDefs st) }
      mainInfo <- maybe (failWith (NoMainFunction mainModule)) pure (Map.lookup mainModule infos)
      (mainLoc, mainId) <- maybe (failWith (NoMainFunction mainModule)) pure
                             (Map.lookup "main" (miKeys mainInfo))
      req <- requirementsOf mainId
      case Map.toList req of
        (r, Trail occ via) : _
          | null via  -> failWith (MissingDefinitionAt occ r)
          | otherwise -> failWith (UnsuppliedRequirement r occ (via <> [("main", mainLoc)]))
        [] -> pure ()
      mainBody <- elaborated mainId
      done <- gets stDone
      let bindings = [ (locatedName (locatedNameLoc key) (topLevelName name (locatedNameText key)), body)
                     | name <- order
                     , (key, i) <- miBindings (infos Map.! name)
                     , Just (_, body) <- [Map.lookup i done] ]
          rootLoc = case mainBody of l :< _ -> l
      pure $ GeneratedLoc "resolveMain" (Just rootLoc) :< LetUPF bindings mainBody

    moduleCtx infos name = do
      let info = infos Map.! name
          imports = [ (locatedNameText (parsedImportModule d), locatedNameText <$> parsedImportQualifier d, parsedImportLoc d)
                        | ExpandedModuleImport d <- itemsOf name ]
          firsts = nubOn (\(m, q, _) -> (m, q)) imports
          layer (m, q, importLoc) =
            ( importLoc
            , Map.fromList [ (maybe k (\q' -> q' <> "." <> k) q, (loc, EntryTarget i))
                           | (k, (loc, i)) <- Map.toList (miKeys (infos Map.! m)) ] )
          layers = layer <$> firsts
          own = second EntryTarget <$> miKeys info
          ctx = Ctx
            { ctxFrames = BinderFrame ModuleBinder own
                          : (BinderFrame ModuleBinder . snd <$> reverse layers)
                          <> [builtinFrame]
            , ctxQualifiers = Set.fromList (mapMaybe (\(_, q, _) -> q) firsts)
            , ctxModule = name
            }
      -- a later import shadows an earlier one, the module's own
      -- definitions shadow every import
      forM_ (zip [0 :: Int ..] layers) $ \(n, (importLoc, keys)) ->
        forM_ (Map.keys keys) $ \k ->
          forM_ (find (Map.member k . snd) (reverse (take n layers))) $ \(_, earlier) ->
            warn ctx (Shadows importLoc k (fst (earlier Map.! k)))
      forM_ (Map.toList own) $ \(k, (loc, _)) ->
        forM_ (find (Map.member k . snd) (reverse layers)) $ \(_, keys) ->
          unless (generated k) $ warn ctx (Shadows loc k (fst (keys Map.! k)))
      pure ctx

    nubOn f = go Set.empty where
      go _ [] = []
      go seen (x : xs)
        | f x `Set.member` seen = go seen xs
        | otherwise = x : go (Set.insert (f x) seen) xs
