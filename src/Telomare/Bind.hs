{-# LANGUAGE LambdaCase #-}

-- |The name binder: whole-program name resolution with requirements, run
-- after 'Telomare.Expand' and before 'Telomare.Desugar' (see
-- @telomare-name-binder-spec.txt@).
--
-- A definition may mention a name that nothing binds where the definition
-- is written. That name is a requirement of the definition, supplied by
-- whichever binder encloses each place the definition is mentioned. The
-- pass elaborates requirements away by lambda lifting: an open entry
-- @k = body@ with requirements @r1 .. rn@ becomes
-- @k = \\__req_r1 -> .. \\__req_rn -> body@, and each mention of @k@
-- becomes @k a1 .. an@, every @ai@ being @ri@ resolved where @k@ is
-- mentioned. A requirement that reaches @main@ unsupplied is an error.
--
-- Scopes are lexical. A module's chain, innermost first, is its own
-- top-level definitions (one store), then its imports with the last
-- written innermost, then the builtins. Imports are not re-exported.
-- Lambda and pattern variables never supply a requirement; since every
-- later stage has one namespace, a variable that could capture a supplied
-- argument is renamed.
--
-- The output is one closed term: every module's top-level definitions,
-- under names unique to their module, in a let around @main@'s body —
-- the shape 'Telomare.Resolve.resolveMain' always produced.
module Telomare.Bind
  ( BindWarning (..)
  , renderBindWarning
  , bindWarningLoc
  , bindProgram
  , requirementParam
  ) where

import Control.Comonad.Cofree (Cofree (..))
import Control.Monad (forM, forM_, unless, when)
import Control.Monad.State.Strict (StateT, gets, modify', runStateT)
import Control.Monad.Trans (lift)
import Data.Bifunctor (second)
import Data.Fix (Fix (..))
import Data.List (find, isPrefixOf)
import Data.Map.Strict (Map)
import qualified Data.Map.Strict as Map
import Data.Maybe (fromMaybe, mapMaybe)
import Data.Set (Set)
import qualified Data.Set as Set
import Telomare.Desugar (builtinNames)
